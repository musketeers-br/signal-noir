"""Export contracts/case-state-machine.yaml as the JSON fixture of the Core's parity test.

Usage (from the repo root):
    uv run --with pyyaml python contracts/tools/export_state_machine_json.py [--xdata]

Writes tests/fixtures/case-state-machine.json. With --xdata it also writes
tests/SignalNoir/Tests/Core/TableFixture.cls, a class carrying the same JSON in an XData block, for
when %UnitTest cannot read files inside the container (specs/002-case-state-machine-core plan, S3).
The Core never reads either file; only the tests do.
"""

import argparse
import json
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[2]
DEFAULT_TABLE = ROOT / "contracts" / "case-state-machine.yaml"
DEFAULT_JSON = ROOT / "tests" / "fixtures" / "case-state-machine.json"
DEFAULT_CLASS = ROOT / "tests" / "SignalNoir" / "Tests" / "Core" / "TableFixture.cls"

CLASS_TEMPLATE = """/// Generated by contracts/tools/export_state_machine_json.py from contracts/case-state-machine.yaml.
/// Do not edit: re-run the export. Fallback fixture for the parity test when files cannot be read
/// in the container (specs/002-case-state-machine-core plan, S3).
Class SignalNoir.Tests.Core.TableFixture Extends %RegisteredObject
{{

/// Returns the normative table as a dynamic object.
ClassMethod Load() As %DynamicObject
{{
    set xdata = ##class(%Dictionary.CompiledXData).%OpenId($classname()_"||Table")
    quit ##class(%DynamicObject).%FromJSON(xdata.Data)
}}

XData Table [ MimeType = application/json ]
{{
{json}
}}

}}
"""


def to_json(table_path):
    table = yaml.safe_load(Path(table_path).read_text(encoding="utf-8"))
    table["version"] = str(table.get("version"))
    return table


def export(table_path=DEFAULT_TABLE, json_path=DEFAULT_JSON, class_path=None):
    table = to_json(table_path)
    text = json.dumps(table, indent=2, ensure_ascii=False)
    Path(json_path).parent.mkdir(parents=True, exist_ok=True)
    Path(json_path).write_text(text + "\n", encoding="utf-8")
    if class_path is not None:
        Path(class_path).parent.mkdir(parents=True, exist_ok=True)
        Path(class_path).write_text(CLASS_TEMPLATE.format(json=text), encoding="utf-8")
    return table


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--xdata", action="store_true", help="also write the TableFixture class")
    args = parser.parse_args()
    export(DEFAULT_TABLE, DEFAULT_JSON, DEFAULT_CLASS if args.xdata else None)
    print(f"wrote {DEFAULT_JSON.relative_to(ROOT)}" + (f" and {DEFAULT_CLASS.relative_to(ROOT)}" if args.xdata else ""))
    return 0


if __name__ == "__main__":
    sys.exit(main())
